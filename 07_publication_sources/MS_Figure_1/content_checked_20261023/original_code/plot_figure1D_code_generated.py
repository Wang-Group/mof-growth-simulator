from __future__ import annotations

import csv
import re
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.lines import Line2D


HERE = Path(__file__).resolve().parent
DATA = HERE / "figure1D_data.csv"
OUT = HERE / "Figure1D_MOF808_1000nm_code_generated.svg"
PNG = HERE / "Figure1D_MOF808_1000nm_code_generated.png"

# The values are kept in a separate CSV so the correction is reproducible and
# the MOF-808 endpoint is not edited inside a pre-existing vector file.
df = pd.read_csv(DATA)

mpl.rcParams.update(
    {
        "font.family": "Arial",
        "font.size": 8.2,
        "svg.fonttype": "none",
        "axes.linewidth": 0.75,
        "xtick.major.width": 0.6,
        "ytick.major.width": 0.7,
        "xtick.major.size": 2.0,
        "ytick.major.size": 2.0,
        "xtick.direction": "out",
        "ytick.direction": "out",
    }
)

# Dimensions and axes placement follow the accepted Figure 1D Matplotlib
# panel geometry (320 pt x 267.874 pt); no SVG is read as a drawing source.
fig = plt.figure(figsize=(320 / 72, 267.874016 / 72), facecolor="white")
ax = fig.add_axes(
    [70.029921 / 320, (267.874016 - (391.889764 - 180)) / 267.874016,
     (297.964919 - 70.029921) / 320, (391.889764 - 210.827145) / 267.874016],
    facecolor="#f6f9fc",
)

labels = df["framework"].tolist()
y = list(range(len(df) - 1, -1, -1))
ax.set_xscale("log")
ax.set_xlim(25, 2500)
ax.set_ylim(-0.4, 8.4)
ax.set_yticks(y)
ax.set_yticklabels(labels)
ax.set_xticks([100, 1000])
ax.set_xticklabels(["100", "1000"])
ax.set_xlabel("Reported primary-crystal size (nm, log scale)", fontsize=9, labelpad=8)
ax.set_title("Within-paper enlargement", loc="left", fontsize=9.8, fontweight="bold", pad=5)

for row, yy in zip(df.itertuples(index=False), y):
    ax.plot(
        [row.lower_nm, row.higher_nm], [yy, yy],
        color="#aeb8c2", lw=1.6, solid_capstyle="round", zorder=1,
    )
    ax.scatter(
        [row.lower_nm], [yy], s=34, facecolors="white", edgecolors="#7a838c",
        linewidths=1.1, zorder=3,
    )
    ax.scatter(
        [row.higher_nm], [yy], s=38, facecolors="#2c7fb8", edgecolors="white",
        linewidths=0.6, zorder=4,
    )
    ax.annotate(
        f"{row.higher_nm:g}", (row.higher_nm, yy),
        xytext=(3.35, -1.5), textcoords="offset points",
        ha="left", va="center", fontsize=7.8, color="#17365d",
    )

ax.tick_params(axis="both", which="major", pad=3)
ax.spines["top"].set_visible(False)
ax.spines["right"].set_visible(False)

# Reproduce the original two-entry legend with the marker symbols generated by
# Matplotlib, rather than placing a text-only annotation below the axes.
legend_handles = [
    Line2D([0], [0], marker="o", linestyle="None", markersize=5.83,
           markerfacecolor="white", markeredgecolor="#7a838c",
           markeredgewidth=1.1, label="lower acid"),
    Line2D([0], [0], marker="o", linestyle="None", markersize=6.16,
           markerfacecolor="#2c7fb8", markeredgecolor="white",
           markeredgewidth=0.6, label="higher acid"),
]
fig.legend(
    handles=legend_handles, loc="lower center", bbox_to_anchor=(0.5, 0.035),
    ncol=2, frameon=False, fontsize=8, handletextpad=0.7,
    columnspacing=1.35, borderaxespad=0,
)

fig.savefig(OUT, format="svg", facecolor="white")
fig.savefig(PNG, format="png", dpi=600, facecolor="white")
plt.close(fig)

# Keep the standalone panel's coordinate convention identical to the accepted
# manuscript panel: the panel occupies y=180..447.874 in the parent Figure 1
# canvas. This is a coordinate-system change applied to the freshly generated
# drawing, not a crop or an edit of an existing SVG.
svg = OUT.read_text(encoding="utf-8")
svg = svg.replace('viewBox="0 0 320 267.874016"', 'viewBox="0 180 320 267.874016"')
svg = re.sub(
    r'<g id="figure_1">',
    '<g id="figure_1" transform="translate(0 180)">',
    svg,
    count=1,
)
OUT.write_text(svg, encoding="utf-8")

print(f"wrote {OUT}")
print(f"wrote {PNG}")
